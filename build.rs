//! Build script that records build provenance for the Python package.
//!
//! Maturin drives the build, and Cargo runs this script as part of it.
//! It writes `pysrc/bytewax/_build_info.py`, which is packaged into
//! wheels and sdists, so users can inspect `bytewax.__version__`,
//! `bytewax.__git_revision__`, and `bytewax.__git_dirty__` without
//! needing Git installed or the original source checkout.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Run a git command in the manifest directory and return its stdout,
/// or `None` if git is unavailable or the command fails (e.g. when
/// building from an sdist without a `.git` directory).
fn git_output(args: &[&str], manifest_dir: &Path) -> Option<String> {
    let output = Command::new("git")
        .args(args)
        .current_dir(manifest_dir)
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    Some(String::from_utf8_lossy(&output.stdout).trim().to_string())
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    // The version in `Cargo.toml`; this is the same value Maturin uses
    // as the distribution version.
    let version = env::var("CARGO_PKG_VERSION").unwrap();

    let git_revision = git_output(&["rev-parse", "HEAD"], &manifest_dir)
        .filter(|revision| !revision.is_empty())
        .unwrap_or_else(|| "unknown".to_string());
    let git_dirty = git_output(&["status", "--porcelain"], &manifest_dir)
        .map_or(false, |status| !status.is_empty());
    // Python spells booleans differently than Rust.
    let git_dirty = if git_dirty { "True" } else { "False" };

    let contents = format!(
        "# This file is generated by `build.rs` at build time. Do not edit.\n\
         \n\
         __version__ = \"{version}\"\n\
         __git_revision__ = \"{git_revision}\"\n\
         __git_dirty__ = {git_dirty}\n"
    );

    let out_path = manifest_dir
        .join("pysrc")
        .join("bytewax")
        .join("_build_info.py");
    // Never fail the build because provenance could not be recorded;
    // `bytewax/__init__.py` falls back gracefully when this file is
    // missing.
    let _ = fs::write(&out_path, contents);

    // Re-run when the checked-out revision changes so the recorded
    // values do not go stale across incremental builds.
    println!("cargo:rerun-if-changed=.git/HEAD");
}
